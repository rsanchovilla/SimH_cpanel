        NAM     PROM LPT
        OPT     O,NOM,NOP 
*
*THIS PROGRAM PATCHES THE DRIVE CONTROLLER 
*PROM TO SUPPORT LINE PRINTER DEVICE
*ALSO PATCHES THE PROM TO SUPPORT EDOS 2.6
*(LOADED EXEC IS BIGGER)
* 
*THIS CODE IS MISSING FROM ORIGINAL PROM, BUT
*EXPECTED TO BE THERE BY EDOS-II
*
PIAS    EQU     $EC26     PRINTER PIA STATUS/COMMAND REGISTER
PIAD    EQU     $EC27     PRINTER PIA DATA REGISTER
*
        ORG     $EAB0
*
LPTC    PSH A             EDOS ROM LINE PRINTER PRINT 1 CHARACTER
LPTCW   LDA A   PIAS      GET PIA STATUS
        AND A   #$02
        BEQ     LPTCW  
        PUL A
        STA A   PIAD      WRITE PIA DATA
        RTS
*
        ORG     $EAD5
*
LDATA   LDA A   #$0D      EDOS ROM LINE PRINTER PRINT STRING WITH LEADING CR-LF
        BSR     LPTC
        LDA A   #$0A
        BSR     LPTC
*
LDATA1  LDA A   0,X      EDOS ROM LINE PRINTER PRINT STRING 
        CMP A   #$04
        BEQ     LDATEX
        BSR     LPTC
        INX
        BRA     LDATA1
LDATEX  RTS
* 
*SET EXPECTED SIZE OF EXEC WHEN RELOADING EDOS
*
        ORG     $E846
        FCB     90       SET ISIZE=90 INSTEAD OF 78
*
        END

* SUBROUTINE TO WRITE A BYTE TO DISK.
* EXPECTS BYTE IN A-REGISTER
*
WRT EQU *
 STAA DKDOD OUTPUT DATA
 LDAA #$30
 STAA DKCOD
 INC OCNTR INCR BFR COUNT
 LDAA OCNTR =128?
 CMPA #128
 BEQ WRT4 YES
 RTS  NO-EXIT
*
WRT4 CLR OCNTR CLR COUNT
*
WRT1 LDAA OSCTR XMIT U/S
 JSR XUS
 JSR CHK MAKE SURE A DISK
 LDAA #5 SET TRY COUNT=5
 STAA TEMP+4
 LDAA OTRK SEEK TRACK
 JSR SEEK
*
WRT2 LDAA #4 WRITE DATA
 JSR LOOP
 LDAA #6 READ FOR CRC
 JSR LOOP
 LDAA DKDID CRC ERROR?
 ANDA #8
 BEQ WRT3 NO
 JSR RFLAG YES-RESET FLAG
 DEC TEMP+4 DECR TRY COUNT
 BNE WRT2 TRY AGAIN
 LDAA #$E WRTIE AS DD
 JSR LOOP
 JSR WRTN INCR DA & CHK SIZE
 BRA WRT1
*
WRT3 JSR WRTN
 RTS

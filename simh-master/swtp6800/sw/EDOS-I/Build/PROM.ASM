*
* SUBROUTINE TO READ AN 8-BIT BYTE FROM DISK & RETURN
* IT IN A-REGISTER. IF EOF, CARRY IS SET.
*
RI EQU *
 TST ICNTR COUNT=0
 BNE RI10 NO
*
RI5 LDX #ITRK
 JSR INCDA
 LDX ISIZE DECR & CHK IFILE SIZE
 DEX
 BNE RI3 OK
 CLR ICNTR
 SEC  SET EOF
 RTS
*
RI3 STX ISIZE
 LDAA ISCTR XMIT U/S
 JSR XUS
 JSR CHK MAKE SURE A DISK
 LDAA #128 SET CNTR =128
 STAA ICNTR
 LDAA #5 SET TRY COUNT=5
 STAA TEMP+4
 LDAA ITRK SEEK TRACK
 JSR SEEK
*
RI6 LDAA #2 READ DATA
 JSR LOOP
 LDAA DKDID DD MARK?
 ANDA #$80
 BEQ RI4 NO
 JSR RFLAG YES-RESET FLAG
 BRA RI5 GO TO NEXT SECTOR
*
RI4 LDAA DKDID CRC ERROR
 ANDA #$8
 BEQ RI10 NO
 JSR RFLAG YES-RESET FLAG
 DEC TEMP+4 DECR TRIES
 BNE RI6 TRY AGAIN
 LDAA #1 CAN'T READ MEDIA
 JMP CHK1
*
RI10 LDAA #$3C SET CMD CNTRL
 STAA DKCOC
 LDAA #$40 SET FOR READ DATA
 STAA DKCOD
 LDAA DKDID READ DATA
 PSHA
 LDAA #$2C RESET CMD CNTRL
 STAA DKCOC
 LDAA #$40 STROBE BFR
 STAA DKCOD
 CLR DKCOD
 DEC ICNTR DECR READ CNTR
 PULA
 CLC
 RTS

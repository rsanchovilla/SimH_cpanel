*SUBROUTINE TO INCR DA. TRACK IN 0,X, SECTOR IN 1,X
*
INCDA EQU *
 INC 1,X
 LDAA 1,X SECTOR=27?
 ANDA #$1F
 CMPA #27
 BEQ INCDB YES
 RTS  NO
*
INCDB LDAA  1,X
 ANDA #$C1 SET SCTR=1
 STAA 1,X
 INC  0,X INCR TRACK
 RTS

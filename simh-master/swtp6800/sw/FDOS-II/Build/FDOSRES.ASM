* INTERPASS FUNCTION
 SPC 2
* IF BIT 0 OF (PASS) = 1 THEN BIT 0 OF (PASS)
* IS SET TO 0 AND 31HEX IS RETURNED IN A-REG.
*
* IF BIT 0 OF (PASS) IS 0 THEN (PASS) IS SET
* TO 00 AND (30HEX + (PASS) SHIFTED RIGHT ONE
* BIT POSITION) IS RETURNED IN A-REG.
*
* IF (PASS) = 00 THEN JUMP TO UPDATE OCCURRS.
 SPC 2
IPASS EQU *
 SPC 1
 LDX #PASS
 LDA A #1
 BIT A X
 BEQ PASS2
 DEC X
PASS3 ADD A #$30
 RTS
 SPC 1
PASS2 TST 0,X
 BEQ PASS4
 JSR RESTR
 LDX #PASS
 CLC
 ROR X
 LDA A X
 CLR X
 BRA PASS3
 SPC 1
PASS4 JMP $43

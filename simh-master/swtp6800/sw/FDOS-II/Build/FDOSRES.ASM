*  SUBROUTINE TO READ AN 8-BIT BYTE FROM DISK &
*  RETURN IT IN A-REGISTER. IF EOF, CARRY IS SET.
  SPC 3
RI EQU *
  TST ICNTR COUNT=0
  BNE RI10 NO
RI5 LDX #ITRK
  JSR INCDA
  LDX ISIZE DECR & CHK IFILE SIZE
 DEX
  BNE RI3 OK
  CLR ICNTR
  SEC SET EOF
  RTS
  SPC 1
RI3 STX ISIZE
 LDAA ISCTR XMIT U/S
  JSR XUS
  JSR CHK MAKE SURE A DISK
  LDAA #128 SET CNTR =128
  STAA ICNTR
  LDAA #5 SET TRY COUNT=5
  STAA TEMP+4
  LDAA ITRK SEEK TRACK
  JSR SEEK
RI6 LDAA #2 READ DATA
  JSR LOOP
 JSR SAVE
  LDAA 0,X DD MARK?
 LDX SAVXR
  ANDA #$80
  BEQ RI4 NO
  JSR RFLAG YES-RESET FLAG
  BRA RI5 GO TO NEXT SECTOR
  SPC 1
RI4 JSR SAVE
 LDAA 0,X CRC ERROR
 LDX SAVXR
  ANDA #$8
  BEQ RI10 NO
  JSR RFLAG YES-RESET FLAG
  DEC TEMP+4 DECR TRIES
  BNE RI6 TRY AGAIN
RI2  LDAA #1 CAN'T READ MEDIA
  JMP CHK1
  SPC 1
RI10 LDAA #$3C SET CMD CNTRL
 BSR SAVE
  STAA 3,X
  LDAA #$40 SET FOR READ DATA
  STAA 2,X
  LDAA 0,X READ DATA
  PSHA
  LDAA #$2C RESET CMD CNTRL
  STAA 3,X
  LDAA #$40 STROBE BFR
  STAA 2,X
  CLR 2,X
 LDX SAVXR
  DEC ICNTR DECR READ CNTR
  PULA
  CLC
  RTS
  SPC 5
*  SUBROUTINE TO WRITE A BYTE TO DISK.
*  EXPECTS BYTE IN A-REGISTER
  SPC 3
WRT EQU *
 BSR SAVE
  STAA 6,X OUTPUT DATA
  LDAA #$30
  STAA 2,X
 LDX SAVXR
  INC OCNTR INCR BFR COUNT
  LDAA OCNTR =128?
  CMPA #128
  BEQ WRT4 YES
  RTS NO-EXIT
  SPC 1
WRT4 CLR OCNTR CLR COUNT
WRT1 LDAA OSCTR XMIT U/S
  JSR XUS
  JSR CHK MAKE SURE A DISK
  LDAA #5 SET TRY COUNT=5
  STAA TEMP+4
  LDAA OTRK SEEK TRACK
  JSR SEEK
WRT2 LDAA #4 WRITE DATA
  JSR LOOP
  LDAA #6 READ FOR CRC
  JSR LOOP
 BSR SAVE
  LDAA 0,X CRC ERROR?
 LDX SAVXR
  ANDA #8
  BEQ WRT3 NO
  JSR RFLAG YES-RESET FLAG
  DEC TEMP+4 DECR TRY COUNT
  BNE WRT2 TRY AGAIN
  LDAA #$E WRTIE AS DD
  JSR LOOP
  JSR WRTN INCR DA & CHK SIZE
  BRA WRT1
WRT3 JSR WRTN
  RTS

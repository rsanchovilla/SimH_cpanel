* PROGRAM TO LOAD AN OBJECT FILE 
*  INTO MEMORY
  SPC 3
REDX EQU *
  JSR RIX GET A CHAR
 BCS REDX3
 CMP A #$53
 BNE REDX NO
  CLR TEMP+2 RESET CHKSM
  JSR RIX GET A CHAR
  BCS REDX2 LOAD ERROR
  CMPA #$30
  BEQ REDX HDR BLK-SKIP
  CMPA #$31
  BEQ REDX4 DATA BLK
  CMPA #$39
  BEQ REDX EOF BLK-SKIP
  CMPA #$1B ESC?
  BNE REDX2
  JSR RIX
  CMP A #$14
  BEQ REDX3 YES-END OF OBJECT FILE
REDX2 LDAA #$3F LOAD ERROR
  JSR CO
  JMP MNTR
  SPC 2
REDX3 RTS
  SPC 1
REDX4 BSR RDBYT GET BYTE COUNT
  DECA DECR COUNT
  STAA TEMP+3 SAVE CNT
  BSR RDBYT READ ADDR(H)
  STAA TEMP
  BSR RDBYT READ ADDR(L)
 LDAB TEMP
 ADDA OFFSET+1
 ADCB OFFSET ADD LOAD OFFSET
 STAB TEMP
  STAA TEMP+1
REDX5 TST TEMP+3 COUNT=0?
  BEQ REDX6 YES
  BSR RDBYT NO-READ DATA
  LDX TEMP
  STAA X SAVE IT
 INX INCR ADDRESS
 STX TEMP
  BRA REDX5 CONTINUE
REDX6 BSR RDBYT READ CHKSM
  INC TEMP+2
  BNE REDX2 CHKSM ERROR
  BRA REDX CHKSM OK
  SPC 4
